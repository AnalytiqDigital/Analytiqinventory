#!/usr/bin/env node
// Generate the vendor's Ed25519 keypair once per product line.
//
//   pnpm --filter @analytiq/licensing keygen
//
// The private key is written to <repo>/.secrets/license-private.pem (ignored by
// git) and must be backed up somewhere safe: without it no new licenses can be
// issued. The public key is written into src/publicKey.ts, which is safe to
// commit. Rebuild and repackage the app after running this.

import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const secretsDir = join(root, '.secrets');
const privatePath = join(secretsDir, 'license-private.pem');
const publicSource = join(here, '..', 'src', 'publicKey.ts');

const force = process.argv.includes('--force');
if (existsSync(privatePath) && !force) {
  console.error(
    `Refusing to overwrite ${privatePath}.\n` +
      'Rotating it invalidates every license key already issued. Re-run with --force if that is intended.'
  );
  process.exit(1);
}

mkdirSync(secretsDir, { recursive: true });
const { privateKey, publicKey } = generateKeyPairSync('ed25519');
const priv = privateKey.export({ type: 'pkcs8', format: 'pem' });
const pub = publicKey.export({ type: 'spki', format: 'pem' });

writeFileSync(privatePath, priv, { mode: 0o600 });
writeFileSync(
  publicSource,
  `// Generated by scripts/keygen.mjs. This file is safe to commit.\n` +
    `// The matching private key lives in .secrets/license-private.pem and must\n` +
    `// never be committed or shipped.\n\n` +
    `export const LICENSE_PUBLIC_KEY = ${JSON.stringify(pub)};\n`
);

console.log(`Private key: ${privatePath}`);
console.log(`Public key:  ${publicSource}`);
console.log('Back up the private key. Rebuild and repackage the app to embed the public key.');
